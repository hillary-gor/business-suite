create or replace function sales.recompute_invoice_totals(p_invoice_id uuid)
returns void
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  update sales.invoices i
     set subtotal = coalesce(x.subtotal, 0),
         tax_total = coalesce(x.tax_total, 0),
         total = coalesce(x.subtotal, 0) + coalesce(x.tax_total, 0)
    from (
      select invoice_id,
             sum(line_net) as subtotal,
             sum(tax_amount) as tax_total
        from sales.invoice_lines
       where invoice_id = p_invoice_id
       group by invoice_id
    ) x
   where i.id = p_invoice_id
     and i.id = x.invoice_id;

  if not found then
    update sales.invoices
       set subtotal = 0, tax_total = 0, total = 0
     where id = p_invoice_id;
  end if;
end;
$$;

