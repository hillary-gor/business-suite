create or replace function sales.post_receipt(
  p_receipt_id      uuid,
  p_idempotency_key text default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_rct        sales.receipts%rowtype;
  v_customer   app.customers%rowtype;
  v_ar         uuid;
  v_bank       gl.accounts%rowtype;
  v_entry_id   uuid;
  v_receipt_no text;
  v_allocated  app.money_amount;
  v_open       app.money_amount;
  v_alloc      record;
begin
  perform app.require_permission(
    (select entity_id from sales.receipts where id = p_receipt_id),
    'sales.payment.create'
  );

  select * into v_rct from sales.receipts where id = p_receipt_id for update;
  if not found then
    raise exception 'Receipt % does not exist', p_receipt_id using errcode = 'no_data_found';
  end if;
  if v_rct.status = 'POSTED' then
    return v_rct.journal_entry_id;
  end if;
  if v_rct.status <> 'DRAFT' then
    raise exception 'Only a draft receipt can be posted' using errcode = 'restrict_violation';
  end if;

  select * into v_customer from app.customers where id = v_rct.customer_id;
  if v_customer.entity_id <> v_rct.entity_id then
    raise exception 'Customer does not belong to this entity' using errcode = 'restrict_violation';
  end if;

  select * into v_bank from gl.accounts where id = v_rct.bank_account_id;
  if not found or v_bank.entity_id <> v_rct.entity_id or not v_bank.is_postable then
    raise exception 'Bank account is not a postable account of this entity'
      using errcode = 'restrict_violation';
  end if;
  if v_bank.control_type is distinct from 'BANK' and v_bank.control_type is distinct from 'CASH' then
    raise exception 'Receipts must be deposited to a cash or bank account'
      using errcode = 'restrict_violation';
  end if;

  v_ar := coalesce(
    v_customer.ar_account_id,
    (select a.id from gl.accounts a
      where a.entity_id = v_rct.entity_id
        and a.control_type = 'ACCOUNTS_RECEIVABLE'
        and a.is_postable
      order by a.code
      limit 1)
  );

  select coalesce(sum(amount), 0) into v_allocated
    from sales.receipt_allocations
   where receipt_id = v_rct.id;

  if v_allocated > v_rct.amount then
    raise exception 'Allocations (%) exceed the receipt amount (%)', v_allocated, v_rct.amount
      using errcode = 'check_violation';
  end if;

  for v_alloc in
    select a.invoice_id, a.amount, i.invoice_no, i.status, i.customer_id, i.currency_code, b.outstanding
      from sales.receipt_allocations a
      join sales.invoices i on i.id = a.invoice_id
      join sales.v_invoice_balances b on b.id = i.id
     where a.receipt_id = v_rct.id
  loop
    if v_alloc.status <> 'ISSUED' then
      raise exception 'Receipts can only be applied to issued invoices'
        using errcode = 'restrict_violation';
    end if;
    if v_alloc.customer_id <> v_rct.customer_id then
      raise exception 'Invoice % belongs to a different customer', v_alloc.invoice_no
        using errcode = 'restrict_violation';
    end if;
    if v_alloc.currency_code <> v_rct.currency_code then
      raise exception 'Invoice % is in %; this receipt is in %',
        v_alloc.invoice_no, v_alloc.currency_code, v_rct.currency_code
        using errcode = 'check_violation';
    end if;
    if v_alloc.amount > v_alloc.outstanding then
      raise exception 'Allocation of % to invoice % exceeds the outstanding %',
        v_alloc.amount, v_alloc.invoice_no, v_alloc.outstanding
        using errcode = 'check_violation';
    end if;
  end loop;

  v_receipt_no := app.next_document_number(v_rct.entity_id, 'RCT', v_rct.receipt_date);

  v_entry_id := gl.post_entry(
    v_rct.entity_id,
    jsonb_build_object(
      'entry_date',         v_rct.receipt_date,
      'source_type',        'CUSTOMER_RECEIPT',
      'source_id',          v_rct.id,
      'source_document_no', v_receipt_no,
      'description',        'Receipt ' || v_receipt_no || ' · ' || v_customer.legal_name,
      'lines', jsonb_build_array(
        jsonb_build_object(
          'account_id',    v_rct.bank_account_id,
          'currency_code', v_rct.currency_code,
          'debit',         v_rct.amount,
          'credit',        0,
          'memo',          coalesce(v_rct.memo, 'Customer receipt'),
          'customer_id',   v_rct.customer_id
        ),
        jsonb_build_object(
          'account_id',    v_ar,
          'currency_code', v_rct.currency_code,
          'debit',         0,
          'credit',        v_rct.amount,
          'memo',          'Accounts receivable',
          'customer_id',   v_rct.customer_id
        )
      )
    ),
    p_idempotency_key
  );

  perform set_config('sales.allow_status_change', 'on', true);

  update sales.receipts
     set status = 'POSTED',
         receipt_no = v_receipt_no,
         journal_entry_id = v_entry_id
   where id = v_rct.id;

  perform set_config('sales.allow_status_change', '', true);

  return v_entry_id;
end;
$$;

comment on function sales.post_receipt(uuid, text) is
  'Posts a draft receipt: DR cash/bank, CR AR. Allocations match open invoices and do not post again.';

create or replace function sales.reverse_receipt(
  p_receipt_id uuid,
  p_reason     text
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_rct      sales.receipts%rowtype;
  v_entry_id uuid;
  v_reason   text := btrim(coalesce(p_reason, ''));
begin
  perform app.require_permission(
    (select entity_id from sales.receipts where id = p_receipt_id),
    'sales.payment.reverse'
  );

  if length(v_reason) < 10 then
    raise exception 'A reversal needs a reason of at least ten characters'
      using errcode = 'check_violation';
  end if;

  select * into v_rct from sales.receipts where id = p_receipt_id for update;
  if not found then
    raise exception 'Receipt % does not exist', p_receipt_id using errcode = 'no_data_found';
  end if;
  if v_rct.status <> 'POSTED' then
    raise exception 'Only a posted receipt can be reversed' using errcode = 'restrict_violation';
  end if;

  v_entry_id := gl.reverse_entry(v_rct.journal_entry_id, v_reason, null, null);

  perform set_config('sales.allow_status_change', 'on', true);

  update sales.receipts
     set status = 'REVERSED',
         reverse_reason = v_reason,
         reversed_at = now(),
         reversed_by = app.acting_user_id()
   where id = v_rct.id;

  perform set_config('sales.allow_status_change', '', true);

  return v_entry_id;
end;
$$;

create or replace function sales.save_invoice(p_entity_id uuid, p_payload jsonb)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_id         uuid := nullif(p_payload ->> 'invoice_id', '')::uuid;
  v_customer   uuid := (p_payload ->> 'customer_id')::uuid;
  v_date       date := (p_payload ->> 'invoice_date')::date;
  v_due        date;
  v_currency   char(3);
  v_terms      uuid := nullif(p_payload ->> 'payment_terms_id', '')::uuid;
  v_line       jsonb;
  v_line_no    integer := 0;
  v_qty        numeric;
  v_price      numeric;
  v_net        numeric;
  v_tax        numeric;
  v_rate       numeric;
  v_tax_id     uuid;
  v_status     sales.invoice_status;
begin
  perform app.require_permission(p_entity_id, 'sales.invoice.create');

  if v_customer is null or v_date is null then
    raise exception 'customer_id and invoice_date are required' using errcode = 'null_value_not_allowed';
  end if;

  if not exists (
    select 1 from app.customers c
     where c.id = v_customer and c.entity_id = p_entity_id
  ) then
    raise exception 'Customer was not found in this entity' using errcode = 'no_data_found';
  end if;

  select coalesce(nullif(p_payload ->> 'currency_code', ''), c.currency_code)
    into v_currency
    from app.customers c
   where c.id = v_customer;

  if v_terms is not null then
    select (v_date + make_interval(days => t.days_net))::date into v_due
      from app.payment_terms t
     where t.id = v_terms and t.entity_id = p_entity_id;
  end if;
  v_due := coalesce((nullif(p_payload ->> 'due_date', ''))::date, v_due, v_date);

  if v_id is not null then
    select status into v_status from sales.invoices where id = v_id and entity_id = p_entity_id;
    if not found then
      raise exception 'Invoice was not found' using errcode = 'no_data_found';
    end if;
    if v_status <> 'DRAFT' then
      raise exception 'Only a draft invoice can be saved' using errcode = 'restrict_violation';
    end if;

    update sales.invoices
       set customer_id = v_customer,
           invoice_date = v_date,
           due_date = v_due,
           currency_code = v_currency,
           payment_terms_id = v_terms,
           customer_po = nullif(p_payload ->> 'customer_po', ''),
           notes = nullif(p_payload ->> 'notes', ''),
           updated_by = app.acting_user_id()
     where id = v_id;

    delete from sales.invoice_lines where invoice_id = v_id;
  else
    insert into sales.invoices (
      entity_id, customer_id, invoice_date, due_date, currency_code,
      payment_terms_id, customer_po, notes, created_by, updated_by
    ) values (
      p_entity_id, v_customer, v_date, v_due, v_currency,
      v_terms, nullif(p_payload ->> 'customer_po', ''), nullif(p_payload ->> 'notes', ''),
      app.acting_user_id(), app.acting_user_id()
    )
    returning id into v_id;
  end if;

  if jsonb_typeof(p_payload -> 'lines') = 'array' then
    for v_line in select * from jsonb_array_elements(p_payload -> 'lines')
    loop
      v_line_no := v_line_no + 1;
      v_qty := (v_line ->> 'quantity')::numeric;
      v_price := (v_line ->> 'unit_price')::numeric;
      if v_qty is null or v_qty <= 0 or v_price is null or v_price < 0 then
        raise exception 'Line %: quantity must be positive and unit_price must be zero or more', v_line_no
          using errcode = 'check_violation';
      end if;
      if length(btrim(coalesce(v_line ->> 'description', ''))) = 0 then
        raise exception 'Line %: description is required', v_line_no
          using errcode = 'null_value_not_allowed';
      end if;

      v_net := round(v_qty * v_price, 4);
      v_tax_id := nullif(v_line ->> 'tax_code_id', '')::uuid;
      v_rate := 0;
      if v_tax_id is not null then
        select t.rate into v_rate
          from app.tax_codes t
         where t.id = v_tax_id and t.entity_id = p_entity_id and t.is_active;
        if not found then
          raise exception 'Line %: tax code was not found', v_line_no using errcode = 'no_data_found';
        end if;
      end if;
      v_tax := round(v_net * coalesce(v_rate, 0), 4);

      insert into sales.invoice_lines (
        entity_id, invoice_id, line_no, item_id, description,
        quantity, unit_price, tax_code_id, tax_amount, line_net, revenue_account_id
      ) values (
        p_entity_id, v_id, v_line_no,
        nullif(v_line ->> 'item_id', '')::uuid,
        btrim(v_line ->> 'description'),
        v_qty, v_price, v_tax_id, v_tax, v_net,
        nullif(v_line ->> 'revenue_account_id', '')::uuid
      );
    end loop;
  end if;

  perform sales.recompute_invoice_totals(v_id);
  return v_id;
end;
$$;

create or replace function sales.save_receipt(p_entity_id uuid, p_payload jsonb)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_id       uuid := nullif(p_payload ->> 'receipt_id', '')::uuid;
  v_customer uuid := (p_payload ->> 'customer_id')::uuid;
  v_date     date := (p_payload ->> 'receipt_date')::date;
  v_amount   numeric := (p_payload ->> 'amount')::numeric;
  v_bank     uuid := (p_payload ->> 'bank_account_id')::uuid;
  v_currency char(3);
  v_status   sales.receipt_status;
  v_alloc    jsonb;
begin
  perform app.require_permission(p_entity_id, 'sales.payment.create');

  if v_customer is null or v_date is null or v_amount is null or v_bank is null then
    raise exception 'customer_id, receipt_date, amount and bank_account_id are required'
      using errcode = 'null_value_not_allowed';
  end if;
  if v_amount <= 0 then
    raise exception 'Receipt amount must be greater than zero' using errcode = 'check_violation';
  end if;

  select coalesce(nullif(p_payload ->> 'currency_code', ''), c.currency_code)
    into v_currency
    from app.customers c
   where c.id = v_customer and c.entity_id = p_entity_id;
  if v_currency is null then
    raise exception 'Customer was not found in this entity' using errcode = 'no_data_found';
  end if;

  if v_id is not null then
    select status into v_status from sales.receipts where id = v_id and entity_id = p_entity_id;
    if not found then
      raise exception 'Receipt was not found' using errcode = 'no_data_found';
    end if;
    if v_status <> 'DRAFT' then
      raise exception 'Only a draft receipt can be saved' using errcode = 'restrict_violation';
    end if;

    update sales.receipts
       set customer_id = v_customer,
           receipt_date = v_date,
           currency_code = v_currency,
           amount = v_amount,
           bank_account_id = v_bank,
           memo = nullif(p_payload ->> 'memo', ''),
           updated_by = app.acting_user_id()
     where id = v_id;

    delete from sales.receipt_allocations where receipt_id = v_id;
  else
    insert into sales.receipts (
      entity_id, customer_id, receipt_date, currency_code, amount,
      bank_account_id, memo, created_by, updated_by
    ) values (
      p_entity_id, v_customer, v_date, v_currency, v_amount,
      v_bank, nullif(p_payload ->> 'memo', ''),
      app.acting_user_id(), app.acting_user_id()
    )
    returning id into v_id;
  end if;

  if jsonb_typeof(p_payload -> 'allocations') = 'array' then
    for v_alloc in select * from jsonb_array_elements(p_payload -> 'allocations')
    loop
      insert into sales.receipt_allocations (entity_id, receipt_id, invoice_id, amount)
      values (
        p_entity_id,
        v_id,
        (v_alloc ->> 'invoice_id')::uuid,
        (v_alloc ->> 'amount')::numeric
      );
    end loop;
  end if;

  return v_id;
end;
$$;

create or replace function app.save_customer(p_entity_id uuid, p_payload jsonb)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_id       uuid := nullif(p_payload ->> 'customer_id', '')::uuid;
  v_code     text := btrim(coalesce(p_payload ->> 'code', ''));
  v_name     text := btrim(coalesce(p_payload ->> 'legal_name', ''));
  v_currency char(3);
begin
  perform app.require_permission(p_entity_id, 'masters.manage_customers');

  if v_name = '' then
    raise exception 'legal_name is required' using errcode = 'null_value_not_allowed';
  end if;

  select coalesce(nullif(p_payload ->> 'currency_code', ''), e.base_currency_code)
    into v_currency
    from app.entities e
   where e.id = p_entity_id;

  if v_code = '' then
    v_code := upper(left(regexp_replace(v_name, '[^A-Za-z0-9]+', '', 'g'), 8));
    if v_code = '' then
      v_code := 'CUST';
    end if;
    if exists (select 1 from app.customers where entity_id = p_entity_id and code = v_code) then
      v_code := v_code || '-' || substr(gen_random_uuid()::text, 1, 4);
    end if;
  end if;

  if v_id is not null then
    update app.customers
       set code = v_code,
           legal_name = v_name,
           trading_name = nullif(p_payload ->> 'trading_name', ''),
           tax_pin = nullif(p_payload ->> 'tax_pin', ''),
           currency_code = v_currency,
           payment_terms_id = nullif(p_payload ->> 'payment_terms_id', '')::uuid,
           email = nullif(p_payload ->> 'email', ''),
           phone = nullif(p_payload ->> 'phone', ''),
           notes = nullif(p_payload ->> 'notes', ''),
           updated_by = app.acting_user_id()
     where id = v_id and entity_id = p_entity_id;
    if not found then
      raise exception 'Customer was not found' using errcode = 'no_data_found';
    end if;
    return v_id;
  end if;

  insert into app.customers (
    entity_id, code, legal_name, trading_name, tax_pin, currency_code,
    payment_terms_id, email, phone, notes, created_by, updated_by
  ) values (
    p_entity_id, v_code, v_name, nullif(p_payload ->> 'trading_name', ''),
    nullif(p_payload ->> 'tax_pin', ''), v_currency,
    nullif(p_payload ->> 'payment_terms_id', '')::uuid,
    nullif(p_payload ->> 'email', ''), nullif(p_payload ->> 'phone', ''),
    nullif(p_payload ->> 'notes', ''),
    app.acting_user_id(), app.acting_user_id()
  )
  returning id into v_id;

  return v_id;
end;
$$;

