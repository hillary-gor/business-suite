create or replace view sales.v_invoice_balances
with (security_invoker = true) as
select
  i.id,
  i.entity_id,
  i.total,
  coalesce((
    select sum(a.amount)
      from sales.receipt_allocations a
      join sales.receipts r on r.id = a.receipt_id
     where a.invoice_id = i.id
       and r.status = 'POSTED'
  ), 0) as allocated,
  i.total - coalesce((
    select sum(a.amount)
      from sales.receipt_allocations a
      join sales.receipts r on r.id = a.receipt_id
     where a.invoice_id = i.id
       and r.status = 'POSTED'
  ), 0) as outstanding
from sales.invoices i;

comment on view sales.v_invoice_balances is
  'Issued-invoice outstanding, after posted receipts only. Reversed receipts do not reduce the balance.';

-- ---------------------------------------------------------------------------
-- Mutation guards: drafts may be edited by the application role; issued
-- documents may be touched only from SECURITY DEFINER (current_user <> session_user).
-- ---------------------------------------------------------------------------

create or replace function sales.fn_guard_invoice()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'DRAFT' then
      raise exception 'An issued or voided invoice cannot be deleted'
        using errcode = 'restrict_violation';
    end if;
    return old;
  end if;

  if current_setting('sales.allow_status_change', true) is distinct from 'on' then
    if tg_op = 'UPDATE' and old.status <> 'DRAFT' then
      raise exception 'An issued invoice cannot be amended. Void it if it should not stand.'
        using errcode = 'restrict_violation';
    end if;
    if new.status is distinct from coalesce(old.status, 'DRAFT') then
      raise exception 'Change invoice status through sales.issue_invoice or sales.void_invoice'
        using errcode = 'restrict_violation';
    end if;
  end if;

  return new;
end;
$$;

create trigger invoices_guard
  before insert or update or delete on sales.invoices
  for each row execute function sales.fn_guard_invoice();

create or replace function sales.fn_guard_invoice_line()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
declare
  v_status sales.invoice_status;
begin
  select status into v_status
    from sales.invoices
   where id = coalesce(new.invoice_id, old.invoice_id);

  if v_status <> 'DRAFT'
     and current_setting('sales.allow_status_change', true) is distinct from 'on' then
    raise exception 'Lines on an issued invoice cannot be amended'
      using errcode = 'restrict_violation';
  end if;

  return coalesce(new, old);
end;
$$;

create trigger invoice_lines_guard
  before insert or update or delete on sales.invoice_lines
  for each row execute function sales.fn_guard_invoice_line();

create or replace function sales.fn_guard_receipt()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'DRAFT' then
      raise exception 'A posted receipt cannot be deleted. Reverse it.'
        using errcode = 'restrict_violation';
    end if;
    return old;
  end if;

  if current_setting('sales.allow_status_change', true) is distinct from 'on' then
    if tg_op = 'UPDATE' and old.status <> 'DRAFT' then
      raise exception 'A posted receipt cannot be amended. Reverse it.'
        using errcode = 'restrict_violation';
    end if;
    if new.status is distinct from coalesce(old.status, 'DRAFT') then
      raise exception 'Change receipt status through sales.post_receipt or sales.reverse_receipt'
        using errcode = 'restrict_violation';
    end if;
  end if;

  return new;
end;
$$;

create trigger receipts_guard
  before insert or update or delete on sales.receipts
  for each row execute function sales.fn_guard_receipt();

