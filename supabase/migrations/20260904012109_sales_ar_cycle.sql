create type sales.invoice_status as enum ('DRAFT', 'ISSUED', 'VOIDED');
create type sales.receipt_status as enum ('DRAFT', 'POSTED', 'REVERSED');

create table sales.invoices (
  id                 uuid primary key default gen_random_uuid(),
  entity_id          uuid not null references app.entities (id) on delete restrict,
  invoice_no         text,
  status             sales.invoice_status not null default 'DRAFT',
  customer_id        uuid not null references app.customers (id) on delete restrict,
  invoice_date       date not null,
  due_date           date not null,
  currency_code      char(3) not null references app.currencies (code),
  payment_terms_id   uuid references app.payment_terms (id) on delete restrict,
  customer_po        text,
  notes              text,
  subtotal           app.money_amount not null default 0 check (subtotal >= 0),
  tax_total          app.money_amount not null default 0 check (tax_total >= 0),
  total              app.money_amount not null default 0 check (total >= 0),
  journal_entry_id   uuid references gl.journal_entry (id) on delete restrict,
  void_of_invoice_id uuid references sales.invoices (id) on delete restrict,
  void_reason        text,
  voided_at          timestamptz,
  voided_by          uuid references app.users (id),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  created_by         uuid,
  updated_by         uuid,
  unique (entity_id, invoice_no),
  constraint invoices_issued_has_number check (status = 'DRAFT' or invoice_no is not null),
  constraint invoices_issued_has_journal check (status <> 'ISSUED' or journal_entry_id is not null),
  constraint invoices_void_has_reason check (
    status <> 'VOIDED' or length(btrim(coalesce(void_reason, ''))) > 0
  ),
  constraint invoices_due_on_or_after_invoice check (due_date >= invoice_date)
);

comment on table sales.invoices is
  'Customer invoice. Drafts are ordinary rows. Issue and void go through sales.issue_invoice / sales.void_invoice, which are the only paths that write the ledger.';

