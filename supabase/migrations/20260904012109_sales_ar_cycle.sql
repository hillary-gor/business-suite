-- ===========================================================================
-- Sales receivables cycle: invoices and customer receipts.
--
-- This is the first operational document path on top of the Phase 1 ledger.
-- Quotations, sales orders, picking and eTIMS transmission are not here.
-- An invoice posts AR / revenue / output tax through gl.post_entry. A
-- receipt posts bank / AR the same way. Allocation is sub-ledger matching
-- and does not write the ledger again.
--
-- Stock is not issued from this invoice. A parts invoice that must move a
-- serialised unit will do that through inv.post_movement in a later slice,
-- in the same transaction as the AR posting. Shipping without a certificate
-- is a regulatory event; it is not something to sneak in as a side effect
-- of "create invoice".
-- ===========================================================================

set search_path = pg_catalog, public, extensions;

create schema if not exists sales;

comment on schema sales is
  'Customer documents: invoices, receipts and the allocations that match them. Ledger writes go through gl.post_entry.';

