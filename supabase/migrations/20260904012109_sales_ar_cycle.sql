  ('CUSTOMER_RECEIPT', 'Customer Receipt',  false, 'Payment received from a customer'),
  ('SALES_CREDIT_NOTE','Sales Credit Note', false, 'Credit note against a customer invoice')
on conflict (code) do nothing;

insert into app.document_types (code, name, description) values
  ('INV', 'Sales Invoice',     'Customer-facing invoice number'),
  ('RCT', 'Customer Receipt',  'Customer-facing receipt number'),
  ('SI',  'Sales Invoice JE',  'Journal generated by issuing an invoice'),
  ('CRP', 'Customer Receipt JE','Journal generated by posting a receipt')
on conflict (code) do nothing;

create or replace function gl.document_type_for_source(p_source_type text)
returns text
language sql
immutable
set search_path = pg_catalog, public
as $$
  select case p_source_type
    when 'MANUAL'            then 'JE'
    when 'OPENING_BALANCE'   then 'OB'
    when 'REVERSAL'          then 'REV'
    when 'FX_REVALUATION'    then 'FXR'
    when 'YEAR_END_CLOSE'    then 'YEC'
    when 'STOCK_MOVEMENT'    then 'STK'
    when 'SALES_INVOICE'     then 'SI'
    when 'CUSTOMER_RECEIPT'  then 'CRP'
    when 'SALES_CREDIT_NOTE' then 'SI'
    else 'JE'
  end;
$$;

