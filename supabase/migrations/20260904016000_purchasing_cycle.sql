create or replace function purch.recompute_po_totals(p_po_id uuid)
returns void
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  update purch.purchase_orders po
     set subtotal = coalesce(x.subtotal, 0),
         tax_total = coalesce(x.tax_total, 0),
         total = coalesce(x.subtotal, 0) + coalesce(x.tax_total, 0)
    from (
      select po_id,
             sum(line_net) as subtotal,
             sum(tax_amount) as tax_total
        from purch.purchase_order_lines
       where po_id = p_po_id
       group by po_id
    ) x
   where po.id = p_po_id
     and po.id = x.po_id;

  if not found then
    update purch.purchase_orders
       set subtotal = 0, tax_total = 0, total = 0
     where id = p_po_id;
  end if;
end;
$$;

