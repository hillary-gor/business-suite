create or replace function purch.save_credit(p_entity_id uuid, p_payload jsonb)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_id         uuid := nullif(p_payload ->> 'credit_id', '')::uuid;
  v_supplier   uuid := (p_payload ->> 'supplier_id')::uuid;
  v_date       date := (p_payload ->> 'credit_date')::date;
  v_currency   char(3);
  v_line       jsonb;
  v_line_no    integer := 0;
  v_qty        numeric;
  v_price      numeric;
  v_net        numeric;
  v_tax        numeric;
  v_rate       numeric;
  v_tax_id     uuid;
  v_status     purch.credit_status;
begin
  -- Permission: finance.payment.create
  perform app.require_permission(p_entity_id, 'finance.payment.create');

  if v_supplier is null or v_date is null then
    raise exception 'supplier_id and credit_date are required' using errcode = 'null_value_not_allowed';
  end if;

  select coalesce(nullif(p_payload ->> 'currency_code', ''), s.currency_code)
    into v_currency
    from app.suppliers s
   where s.id = v_supplier and s.entity_id = p_entity_id;
  if v_currency is null then
    raise exception 'Supplier was not found in this entity' using errcode = 'no_data_found';
  end if;

  if v_id is not null then
    select status into v_status from purch.supplier_credits where id = v_id and entity_id = p_entity_id;
    if not found then
      raise exception 'Credit was not found' using errcode = 'no_data_found';
    end if;
    if v_status <> 'DRAFT' then
      raise exception 'Only a draft credit can be saved' using errcode = 'restrict_violation';
    end if;

    update purch.supplier_credits
       set supplier_id = v_supplier,
           credit_date = v_date,
           currency_code = v_currency,
           notes = nullif(p_payload ->> 'notes', ''),
           updated_by = app.acting_user_id()
     where id = v_id;

    delete from purch.supplier_credit_lines where credit_id = v_id;
  else
    insert into purch.supplier_credits (
      entity_id, supplier_id, credit_date, currency_code, notes, created_by, updated_by
    ) values (
      p_entity_id, v_supplier, v_date, v_currency,
      nullif(p_payload ->> 'notes', ''),
      app.acting_user_id(), app.acting_user_id()
    )
    returning id into v_id;
  end if;

  if jsonb_typeof(p_payload -> 'lines') = 'array' then
    for v_line in select * from jsonb_array_elements(p_payload -> 'lines')
    loop
      v_line_no := v_line_no + 1;
      v_qty := (v_line ->> 'quantity')::numeric;
      v_price := (v_line ->> 'unit_price')::numeric;
      if v_qty is null or v_qty <= 0 or v_price is null or v_price < 0 then
        raise exception 'Line %: quantity must be positive and unit_price must be zero or more', v_line_no
          using errcode = 'check_violation';
      end if;
      if length(btrim(coalesce(v_line ->> 'description', ''))) = 0 then
        raise exception 'Line %: description is required', v_line_no
          using errcode = 'null_value_not_allowed';
      end if;

      v_net := round(v_qty * v_price, 4);
      v_tax_id := nullif(v_line ->> 'tax_code_id', '')::uuid;
      v_rate := 0;
      if v_tax_id is not null then
        select t.rate into v_rate
          from app.tax_codes t
         where t.id = v_tax_id and t.entity_id = p_entity_id and t.is_active;
        if not found then
          raise exception 'Line %: tax code was not found', v_line_no using errcode = 'no_data_found';
        end if;
      end if;
      v_tax := round(v_net * coalesce(v_rate, 0), 4);

      insert into purch.supplier_credit_lines (
        entity_id, credit_id, line_no, item_id, description,
        quantity, unit_price, tax_code_id, tax_amount, line_net,
        expense_account_id, stock_unit_id, warehouse_id
      ) values (
        p_entity_id, v_id, v_line_no,
        nullif(v_line ->> 'item_id', '')::uuid,
        btrim(v_line ->> 'description'),
        v_qty, v_price, v_tax_id, v_tax, v_net,
        nullif(v_line ->> 'expense_account_id', '')::uuid,
        nullif(v_line ->> 'stock_unit_id', '')::uuid,
        nullif(v_line ->> 'warehouse_id', '')::uuid
      );
    end loop;
  end if;

  perform purch.recompute_credit_totals(v_id);
  return v_id;
end;
$$;

create or replace function purch.post_credit(
  p_credit_id       uuid,
  p_idempotency_key text default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_credit     purch.supplier_credits%rowtype;
  v_supplier   app.suppliers%rowtype;
  v_ap         uuid;
  v_entry_id   uuid;
  v_credit_no  text;
  v_lines      jsonb := '[]'::jsonb;
  v_line       record;
  v_tax        record;
  v_credit_acct uuid;
  v_key        text;
begin
  -- Permission: finance.payment.create
  perform app.require_permission(
    (select entity_id from purch.supplier_credits where id = p_credit_id),
    'finance.payment.create'
  );

  select * into v_credit from purch.supplier_credits where id = p_credit_id for update;
  if not found then
    raise exception 'Credit % does not exist', p_credit_id using errcode = 'no_data_found';
  end if;
  if v_credit.status = 'POSTED' then
    return v_credit.journal_entry_id;
  end if;
  if v_credit.status <> 'DRAFT' then
    raise exception 'Only a draft credit can be posted' using errcode = 'restrict_violation';
  end if;

  perform purch.recompute_credit_totals(v_credit.id);
  select * into v_credit from purch.supplier_credits where id = v_credit.id;

  if v_credit.total <= 0 then
    raise exception 'A credit needs at least one line with a positive amount'
      using errcode = 'check_violation';
  end if;

  select * into v_supplier from app.suppliers where id = v_credit.supplier_id;
  v_ap := purch.ap_account(v_credit.entity_id, v_credit.supplier_id);

  -- Inventory returns first (SUPPLIER_RETURN undoes RECEIPT valuation against GRNI).
  for v_line in
    select * from purch.supplier_credit_lines
     where credit_id = v_credit.id
       and stock_unit_id is not null
     order by line_no
  loop
    if v_line.warehouse_id is null or v_line.item_id is null then
      raise exception 'Line %: inventory return needs item_id and warehouse_id', v_line.line_no
        using errcode = 'null_value_not_allowed';
    end if;
    if v_line.quantity <> 1 then
      raise exception 'Line %: serialised returns are one unit at a time', v_line.line_no
        using errcode = 'check_violation';
    end if;

    v_key := case
      when p_idempotency_key is not null then p_idempotency_key || ':return:' || v_line.line_no
      else null
    end;

    perform inv.post_movement(
      p_entity_id => v_credit.entity_id,
      p_item_id => v_line.item_id,
      p_warehouse_id => v_line.warehouse_id,
      p_movement_type => 'SUPPLIER_RETURN',
      p_movement_date => v_credit.credit_date,
      p_quantity => -v_line.quantity,
      p_stock_unit_id => v_line.stock_unit_id,
      p_source_type => 'SUPPLIER_CREDIT',
      p_source_id => v_credit.id,
      p_source_line_id => v_line.id,
      p_reference => null,
      p_notes => v_line.description,
      p_idempotency_key => v_key
    );
  end loop;

  -- AP reduction journal: DR AP; CR expense (or GRNI for inventory-return lines); CR input tax.
  v_lines := v_lines || jsonb_build_object(
    'account_id',    v_ap,
    'currency_code', v_credit.currency_code,
    'debit',         v_credit.total,
    'credit',        0,
    'memo',          'Accounts payable',
    'supplier_id',   v_credit.supplier_id
  );

  for v_line in
    select l.*
      from purch.supplier_credit_lines l
     where l.credit_id = v_credit.id
     order by l.line_no
  loop
    if v_line.stock_unit_id is not null then
      v_credit_acct := gl.setting_account(v_credit.entity_id, 'GOODS_RECEIVED_NOT_INVOICED');
    else
      v_credit_acct := purch.resolve_expense_account(v_credit.entity_id, v_line.expense_account_id);
    end if;

    v_lines := v_lines || jsonb_build_object(
      'account_id',    v_credit_acct,
      'currency_code', v_credit.currency_code,
      'debit',         0,
      'credit',        v_line.line_net,
      'memo',          v_line.description,
      'supplier_id',   v_credit.supplier_id,
      'item_id',       v_line.item_id,
      'stock_unit_id', v_line.stock_unit_id
    );
  end loop;

  for v_tax in
    select t.input_tax_account_id as account_id, sum(l.tax_amount) as amount
      from purch.supplier_credit_lines l
      join app.tax_codes t on t.id = l.tax_code_id
     where l.credit_id = v_credit.id
       and l.tax_amount > 0
     group by t.input_tax_account_id
  loop
    if v_tax.account_id is null then
      raise exception 'Tax code is missing an input tax account' using errcode = 'no_data_found';
    end if;
    v_lines := v_lines || jsonb_build_object(
      'account_id',    v_tax.account_id,
      'currency_code', v_credit.currency_code,
      'debit',         0,
      'credit',        v_tax.amount,
      'memo',          'Input tax reversal',
      'supplier_id',   v_credit.supplier_id
    );
  end loop;

  v_credit_no := app.next_document_number(v_credit.entity_id, 'SCR', v_credit.credit_date);

  v_entry_id := gl.post_entry(
    v_credit.entity_id,
    jsonb_build_object(
      'entry_date',         v_credit.credit_date,
      'source_type',        'SUPPLIER_CREDIT',
      'source_id',          v_credit.id,
      'source_document_no', v_credit_no,
      'description',        'Credit ' || v_credit_no || ' · ' || v_supplier.legal_name,
      'lines',              v_lines
    ),
    p_idempotency_key
  );

  perform set_config('purch.allow_status_change', 'on', true);

  update purch.supplier_credits
     set status = 'POSTED',
         credit_no = v_credit_no,
         journal_entry_id = v_entry_id
   where id = v_credit.id;

  perform set_config('purch.allow_status_change', '', true);

  return v_entry_id;
end;
$$;

