create or replace function purch.post_payment(
  p_payment_id      uuid,
  p_idempotency_key text default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_pay        purch.supplier_payments%rowtype;
  v_supplier   app.suppliers%rowtype;
  v_ap         uuid;
  v_bank       gl.accounts%rowtype;
  v_entry_id   uuid;
  v_payment_no text;
  v_allocated  app.money_amount;
  v_alloc      record;
begin
  -- Permission: finance.payment.create
  perform app.require_permission(
    (select entity_id from purch.supplier_payments where id = p_payment_id),
    'finance.payment.create'
  );

  select * into v_pay from purch.supplier_payments where id = p_payment_id for update;
  if not found then
    raise exception 'Payment % does not exist', p_payment_id using errcode = 'no_data_found';
  end if;
  if v_pay.status = 'POSTED' then
    return v_pay.journal_entry_id;
  end if;
  if v_pay.status <> 'DRAFT' then
    raise exception 'Only a draft payment can be posted' using errcode = 'restrict_violation';
  end if;

  select * into v_supplier from app.suppliers where id = v_pay.supplier_id;
  if v_supplier.entity_id <> v_pay.entity_id then
    raise exception 'Supplier does not belong to this entity' using errcode = 'restrict_violation';
  end if;

  select * into v_bank from gl.accounts where id = v_pay.bank_account_id;
  if not found or v_bank.entity_id <> v_pay.entity_id or not v_bank.is_postable then
    raise exception 'Bank account is not a postable account of this entity'
      using errcode = 'restrict_violation';
  end if;
  if v_bank.control_type is distinct from 'BANK' and v_bank.control_type is distinct from 'CASH' then
    raise exception 'Payments must be drawn from a cash or bank account'
      using errcode = 'restrict_violation';
  end if;

  v_ap := purch.ap_account(v_pay.entity_id, v_pay.supplier_id);

  select coalesce(sum(amount), 0) into v_allocated
    from purch.supplier_payment_allocations
   where payment_id = v_pay.id;

  if v_allocated > v_pay.amount then
    raise exception 'Allocations (%) exceed the payment amount (%)', v_allocated, v_pay.amount
      using errcode = 'check_violation';
  end if;

  for v_alloc in
    select a.bill_id, a.amount, b.bill_no, b.status, b.supplier_id, b.currency_code, bal.outstanding
      from purch.supplier_payment_allocations a
      join purch.bills b on b.id = a.bill_id
      join purch.v_bill_balances bal on bal.id = b.id
     where a.payment_id = v_pay.id
  loop
    if v_alloc.status <> 'POSTED' then
      raise exception 'Payments can only be applied to posted bills'
        using errcode = 'restrict_violation';
    end if;
    if v_alloc.supplier_id <> v_pay.supplier_id then
      raise exception 'Bill % belongs to a different supplier', v_alloc.bill_no
        using errcode = 'restrict_violation';
    end if;
    if v_alloc.currency_code <> v_pay.currency_code then
      raise exception 'Bill % is in %; this payment is in %',
        v_alloc.bill_no, v_alloc.currency_code, v_pay.currency_code
        using errcode = 'check_violation';
    end if;
    if v_alloc.amount > v_alloc.outstanding then
      raise exception 'Allocation of % to bill % exceeds the outstanding %',
        v_alloc.amount, v_alloc.bill_no, v_alloc.outstanding
        using errcode = 'check_violation';
    end if;
  end loop;

  v_payment_no := app.next_document_number(v_pay.entity_id, 'SPAY', v_pay.payment_date);

  v_entry_id := gl.post_entry(
    v_pay.entity_id,
    jsonb_build_object(
      'entry_date',         v_pay.payment_date,
      'source_type',        'SUPPLIER_PAYMENT',
      'source_id',          v_pay.id,
      'source_document_no', v_payment_no,
      'description',        'Payment ' || v_payment_no || ' · ' || v_supplier.legal_name,
      'lines', jsonb_build_array(
        jsonb_build_object(
          'account_id',    v_ap,
          'currency_code', v_pay.currency_code,
          'debit',         v_pay.amount,
          'credit',        0,
          'memo',          'Accounts payable',
          'supplier_id',   v_pay.supplier_id
        ),
        jsonb_build_object(
          'account_id',    v_pay.bank_account_id,
          'currency_code', v_pay.currency_code,
          'debit',         0,
          'credit',        v_pay.amount,
          'memo',          coalesce(v_pay.memo, 'Supplier payment'),
          'supplier_id',   v_pay.supplier_id
        )
      )
    ),
    p_idempotency_key
  );

  perform set_config('purch.allow_status_change', 'on', true);

  update purch.supplier_payments
     set status = 'POSTED',
         payment_no = v_payment_no,
         journal_entry_id = v_entry_id
   where id = v_pay.id;

  perform set_config('purch.allow_status_change', '', true);

  return v_entry_id;
end;
$$;

