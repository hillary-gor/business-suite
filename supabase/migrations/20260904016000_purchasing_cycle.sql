create or replace function purch.save_bill(p_entity_id uuid, p_payload jsonb)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_id         uuid := nullif(p_payload ->> 'bill_id', '')::uuid;
  v_supplier   uuid := (p_payload ->> 'supplier_id')::uuid;
  v_date       date := (p_payload ->> 'bill_date')::date;
  v_due        date;
  v_currency   char(3);
  v_terms      uuid := nullif(p_payload ->> 'payment_terms_id', '')::uuid;
  v_line       jsonb;
  v_match      jsonb;
  v_line_no    integer := 0;
  v_qty        numeric;
  v_price      numeric;
  v_net        numeric;
  v_tax        numeric;
  v_rate       numeric;
  v_tax_id     uuid;
  v_status     purch.bill_status;
begin
  -- Permission: finance.payment.create (closest existing; see migration header)
  perform app.require_permission(p_entity_id, 'finance.payment.create');

  if v_supplier is null or v_date is null then
    raise exception 'supplier_id and bill_date are required' using errcode = 'null_value_not_allowed';
  end if;

  if not exists (
    select 1 from app.suppliers s
     where s.id = v_supplier and s.entity_id = p_entity_id
  ) then
    raise exception 'Supplier was not found in this entity' using errcode = 'no_data_found';
  end if;

  select coalesce(nullif(p_payload ->> 'currency_code', ''), s.currency_code)
    into v_currency
    from app.suppliers s
   where s.id = v_supplier;

  if v_terms is not null then
    select (v_date + make_interval(days => t.days_net))::date into v_due
      from app.payment_terms t
     where t.id = v_terms and t.entity_id = p_entity_id;
  end if;
  v_due := coalesce((nullif(p_payload ->> 'due_date', ''))::date, v_due, v_date);

  if v_id is not null then
    select status into v_status from purch.bills where id = v_id and entity_id = p_entity_id;
    if not found then
      raise exception 'Bill was not found' using errcode = 'no_data_found';
    end if;
    if v_status <> 'DRAFT' then
      raise exception 'Only a draft bill can be saved' using errcode = 'restrict_violation';
    end if;

    update purch.bills
       set supplier_id = v_supplier,
           bill_date = v_date,
           due_date = v_due,
           currency_code = v_currency,
           payment_terms_id = v_terms,
           supplier_ref = nullif(p_payload ->> 'supplier_ref', ''),
           notes = nullif(p_payload ->> 'notes', ''),
           updated_by = app.acting_user_id()
     where id = v_id;

    delete from purch.bill_lines where bill_id = v_id;
    delete from purch.bill_receipt_matches where bill_id = v_id;
  else
    insert into purch.bills (
      entity_id, supplier_id, bill_date, due_date, currency_code,
      payment_terms_id, supplier_ref, notes, created_by, updated_by
    ) values (
      p_entity_id, v_supplier, v_date, v_due, v_currency,
      v_terms, nullif(p_payload ->> 'supplier_ref', ''), nullif(p_payload ->> 'notes', ''),
      app.acting_user_id(), app.acting_user_id()
    )
    returning id into v_id;
  end if;

  if jsonb_typeof(p_payload -> 'lines') = 'array' then
    for v_line in select * from jsonb_array_elements(p_payload -> 'lines')
    loop
      v_line_no := v_line_no + 1;
      v_qty := (v_line ->> 'quantity')::numeric;
      v_price := (v_line ->> 'unit_price')::numeric;
      if v_qty is null or v_qty <= 0 or v_price is null or v_price < 0 then
        raise exception 'Line %: quantity must be positive and unit_price must be zero or more', v_line_no
          using errcode = 'check_violation';
      end if;
      if length(btrim(coalesce(v_line ->> 'description', ''))) = 0 then
        raise exception 'Line %: description is required', v_line_no
          using errcode = 'null_value_not_allowed';
      end if;

      v_net := round(v_qty * v_price, 4);
      v_tax_id := nullif(v_line ->> 'tax_code_id', '')::uuid;
      v_rate := 0;
      if v_tax_id is not null then
        select t.rate into v_rate
          from app.tax_codes t
         where t.id = v_tax_id and t.entity_id = p_entity_id and t.is_active;
        if not found then
          raise exception 'Line %: tax code was not found', v_line_no using errcode = 'no_data_found';
        end if;
      end if;
      v_tax := round(v_net * coalesce(v_rate, 0), 4);

      insert into purch.bill_lines (
        entity_id, bill_id, line_no, item_id, description,
        quantity, unit_price, tax_code_id, tax_amount, line_net,
        expense_account_id, goods_receipt_line_id
      ) values (
        p_entity_id, v_id, v_line_no,
        nullif(v_line ->> 'item_id', '')::uuid,
        btrim(v_line ->> 'description'),
        v_qty, v_price, v_tax_id, v_tax, v_net,
        nullif(v_line ->> 'expense_account_id', '')::uuid,
        nullif(v_line ->> 'goods_receipt_line_id', '')::uuid
      );
    end loop;
  end if;

  if jsonb_typeof(p_payload -> 'receipt_matches') = 'array' then
    for v_match in select * from jsonb_array_elements(p_payload -> 'receipt_matches')
    loop
      insert into purch.bill_receipt_matches (
        entity_id, bill_id, goods_receipt_id, amount
      ) values (
        p_entity_id,
        v_id,
        (v_match ->> 'goods_receipt_id')::uuid,
        nullif(v_match ->> 'amount', '')::numeric
      );
    end loop;
  end if;

  perform purch.recompute_bill_totals(v_id);
  return v_id;
end;
$$;

create or replace function purch.post_bill(
  p_bill_id         uuid,
  p_idempotency_key text default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_bill       purch.bills%rowtype;
  v_supplier   app.suppliers%rowtype;
  v_ap         uuid;
  v_grni       uuid;
  v_entry_id   uuid;
  v_bill_no    text;
  v_lines      jsonb := '[]'::jsonb;
  v_line       record;
  v_tax        record;
  v_debit_acct uuid;
  v_grn_line   purch.goods_receipt_lines%rowtype;
  v_grn        purch.goods_receipts%rowtype;
begin
  -- Permission: finance.payment.create (AP bill post; see migration header)
  perform app.require_permission(
    (select entity_id from purch.bills where id = p_bill_id),
    'finance.payment.create'
  );

  select * into v_bill from purch.bills where id = p_bill_id for update;
  if not found then
    raise exception 'Bill % does not exist', p_bill_id using errcode = 'no_data_found';
  end if;
  if v_bill.status = 'POSTED' then
    return v_bill.journal_entry_id;
  end if;
  if v_bill.status <> 'DRAFT' then
    raise exception 'Only a draft bill can be posted' using errcode = 'restrict_violation';
  end if;

  perform purch.recompute_bill_totals(v_bill.id);
  select * into v_bill from purch.bills where id = v_bill.id;

  if v_bill.total <= 0 then
    raise exception 'A bill needs at least one line with a positive amount'
      using errcode = 'check_violation';
  end if;

  select * into v_supplier from app.suppliers where id = v_bill.supplier_id;
  if v_supplier.entity_id <> v_bill.entity_id then
    raise exception 'Supplier does not belong to this entity' using errcode = 'restrict_violation';
  end if;

  v_ap := purch.ap_account(v_bill.entity_id, v_bill.supplier_id);
  v_grni := gl.setting_account(v_bill.entity_id, 'GOODS_RECEIVED_NOT_INVOICED');

  for v_line in
    select l.*, t.input_tax_account_id
      from purch.bill_lines l
      left join app.tax_codes t on t.id = l.tax_code_id
     where l.bill_id = v_bill.id
     order by l.line_no
  loop
    if v_line.goods_receipt_line_id is not null then
      select * into v_grn_line from purch.goods_receipt_lines where id = v_line.goods_receipt_line_id;
      if not found then
        raise exception 'Line %: goods receipt line was not found', v_line.line_no
          using errcode = 'no_data_found';
      end if;
      select * into v_grn from purch.goods_receipts where id = v_grn_line.goods_receipt_id;
      if v_grn.status <> 'POSTED' then
        raise exception 'Line %: goods receipt must be posted before matching', v_line.line_no
          using errcode = 'restrict_violation';
      end if;
      if v_grn.supplier_id <> v_bill.supplier_id then
        raise exception 'Line %: goods receipt belongs to a different supplier', v_line.line_no
          using errcode = 'restrict_violation';
      end if;
      v_debit_acct := v_grni;
    else
      v_debit_acct := purch.resolve_expense_account(v_bill.entity_id, v_line.expense_account_id);
    end if;

    v_lines := v_lines || jsonb_build_object(
      'account_id',    v_debit_acct,
      'currency_code', v_bill.currency_code,
      'debit',         v_line.line_net,
      'credit',        0,
      'memo',          v_line.description,
      'supplier_id',   v_bill.supplier_id,
      'item_id',       v_line.item_id
    );
  end loop;

  for v_tax in
    select t.input_tax_account_id as account_id, sum(l.tax_amount) as amount
      from purch.bill_lines l
      join app.tax_codes t on t.id = l.tax_code_id
     where l.bill_id = v_bill.id
       and l.tax_amount > 0
     group by t.input_tax_account_id
  loop
    if v_tax.account_id is null then
      raise exception 'Tax code is missing an input tax account' using errcode = 'no_data_found';
    end if;
    v_lines := v_lines || jsonb_build_object(
      'account_id',    v_tax.account_id,
      'currency_code', v_bill.currency_code,
      'debit',         v_tax.amount,
      'credit',        0,
      'memo',          'Input tax',
      'supplier_id',   v_bill.supplier_id
    );
  end loop;

  v_lines := v_lines || jsonb_build_object(
    'account_id',    v_ap,
    'currency_code', v_bill.currency_code,
    'debit',         0,
    'credit',        v_bill.total,
    'memo',          'Accounts payable',
    'supplier_id',   v_bill.supplier_id
  );

  v_bill_no := app.next_document_number(v_bill.entity_id, 'BILL', v_bill.bill_date);

  v_entry_id := gl.post_entry(
    v_bill.entity_id,
    jsonb_build_object(
      'entry_date',         v_bill.bill_date,
      'source_type',        'PURCHASE_BILL',
      'source_id',          v_bill.id,
      'source_document_no', v_bill_no,
      'description',        'Bill ' || v_bill_no || ' · ' || v_supplier.legal_name,
      'lines',              v_lines
    ),
    p_idempotency_key
  );

  perform set_config('purch.allow_status_change', 'on', true);

  update purch.bills
     set status = 'POSTED',
         bill_no = v_bill_no,
         journal_entry_id = v_entry_id
   where id = v_bill.id;

  perform set_config('purch.allow_status_change', '', true);

  return v_entry_id;
end;
$$;

