create or replace function purch.fn_guard_po()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'DRAFT' then
      raise exception 'An approved or cancelled purchase order cannot be deleted'
        using errcode = 'restrict_violation';
    end if;
    return old;
  end if;

  if current_setting('purch.allow_status_change', true) is distinct from 'on' then
    if tg_op = 'UPDATE' and old.status <> 'DRAFT' then
      raise exception 'An approved purchase order cannot be amended. Cancel it if it should not stand.'
        using errcode = 'restrict_violation';
    end if;
    if new.status is distinct from coalesce(old.status, 'DRAFT') then
      raise exception 'Change purchase order status through purch.approve_po or purch.cancel_po'
        using errcode = 'restrict_violation';
    end if;
  end if;

  return new;
end;
$$;

create trigger purchase_orders_guard
  before insert or update or delete on purch.purchase_orders
  for each row execute function purch.fn_guard_po();

create or replace function purch.fn_guard_po_line()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
declare
  v_status purch.po_status;
begin
  select status into v_status
    from purch.purchase_orders
   where id = coalesce(new.po_id, old.po_id);

  if v_status <> 'DRAFT'
     and current_setting('purch.allow_status_change', true) is distinct from 'on' then
    raise exception 'Lines on an approved purchase order cannot be amended'
      using errcode = 'restrict_violation';
  end if;

  return coalesce(new, old);
end;
$$;

