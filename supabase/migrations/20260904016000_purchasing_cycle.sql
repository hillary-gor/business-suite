create or replace function purch.save_po(p_entity_id uuid, p_payload jsonb)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_id         uuid := nullif(p_payload ->> 'po_id', '')::uuid;
  v_supplier   uuid := (p_payload ->> 'supplier_id')::uuid;
  v_date       date := (p_payload ->> 'order_date')::date;
  v_currency   char(3);
  v_terms      uuid := nullif(p_payload ->> 'payment_terms_id', '')::uuid;
  v_warehouse  uuid := nullif(p_payload ->> 'warehouse_id', '')::uuid;
  v_line       jsonb;
  v_line_no    integer := 0;
  v_qty        numeric;
  v_price      numeric;
  v_net        numeric;
  v_tax        numeric;
  v_rate       numeric;
  v_tax_id     uuid;
  v_status     purch.po_status;
begin
  -- Permission: procurement.purchase.create
  perform app.require_permission(p_entity_id, 'procurement.purchase.create');

  if v_supplier is null or v_date is null then
    raise exception 'supplier_id and order_date are required' using errcode = 'null_value_not_allowed';
  end if;

  if not exists (
    select 1 from app.suppliers s
     where s.id = v_supplier and s.entity_id = p_entity_id and s.is_active
  ) then
    raise exception 'Supplier was not found in this entity' using errcode = 'no_data_found';
  end if;

  select coalesce(nullif(p_payload ->> 'currency_code', ''), s.currency_code)
    into v_currency
    from app.suppliers s
   where s.id = v_supplier;

  if v_id is not null then
    select status into v_status from purch.purchase_orders where id = v_id and entity_id = p_entity_id;
    if not found then
      raise exception 'Purchase order was not found' using errcode = 'no_data_found';
    end if;
    if v_status <> 'DRAFT' then
      raise exception 'Only a draft purchase order can be saved' using errcode = 'restrict_violation';
    end if;

    update purch.purchase_orders
       set supplier_id = v_supplier,
           order_date = v_date,
           expected_date = nullif(p_payload ->> 'expected_date', '')::date,
           currency_code = v_currency,
           payment_terms_id = v_terms,
           warehouse_id = v_warehouse,
           notes = nullif(p_payload ->> 'notes', ''),
           updated_by = app.acting_user_id()
     where id = v_id;

    delete from purch.purchase_order_lines where po_id = v_id;
  else
    insert into purch.purchase_orders (
      entity_id, supplier_id, order_date, expected_date, currency_code,
      payment_terms_id, warehouse_id, notes, created_by, updated_by
    ) values (
      p_entity_id, v_supplier, v_date, nullif(p_payload ->> 'expected_date', '')::date, v_currency,
      v_terms, v_warehouse, nullif(p_payload ->> 'notes', ''),
      app.acting_user_id(), app.acting_user_id()
    )
    returning id into v_id;
  end if;

  if jsonb_typeof(p_payload -> 'lines') = 'array' then
    for v_line in select * from jsonb_array_elements(p_payload -> 'lines')
    loop
      v_line_no := v_line_no + 1;
      v_qty := (v_line ->> 'quantity')::numeric;
      v_price := (v_line ->> 'unit_price')::numeric;
      if v_qty is null or v_qty <= 0 or v_price is null or v_price < 0 then
        raise exception 'Line %: quantity must be positive and unit_price must be zero or more', v_line_no
          using errcode = 'check_violation';
      end if;
      if length(btrim(coalesce(v_line ->> 'description', ''))) = 0 then
        raise exception 'Line %: description is required', v_line_no
          using errcode = 'null_value_not_allowed';
      end if;

      v_net := round(v_qty * v_price, 4);
      v_tax_id := nullif(v_line ->> 'tax_code_id', '')::uuid;
      v_rate := 0;
      if v_tax_id is not null then
        select t.rate into v_rate
          from app.tax_codes t
         where t.id = v_tax_id and t.entity_id = p_entity_id and t.is_active;
        if not found then
          raise exception 'Line %: tax code was not found', v_line_no using errcode = 'no_data_found';
        end if;
      end if;
      v_tax := round(v_net * coalesce(v_rate, 0), 4);

      insert into purch.purchase_order_lines (
        entity_id, po_id, line_no, item_id, description,
        quantity, unit_price, tax_code_id, tax_amount, line_net
      ) values (
        p_entity_id, v_id, v_line_no,
        nullif(v_line ->> 'item_id', '')::uuid,
        btrim(v_line ->> 'description'),
        v_qty, v_price, v_tax_id, v_tax, v_net
      );
    end loop;
  end if;

  perform purch.recompute_po_totals(v_id);
  return v_id;
end;
$$;

comment on function purch.save_po(uuid, jsonb) is
  'Creates or updates a draft purchase order. Requires procurement.purchase.create.';

create or replace function purch.approve_po(p_po_id uuid)
returns text
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_po       purch.purchase_orders%rowtype;
  v_supplier app.suppliers%rowtype;
  v_po_no    text;
begin
  -- Permission: procurement.purchase.approve
  perform app.require_permission(
    (select entity_id from purch.purchase_orders where id = p_po_id),
    'procurement.purchase.approve'
  );

  select * into v_po from purch.purchase_orders where id = p_po_id for update;
  if not found then
    raise exception 'Purchase order % does not exist', p_po_id using errcode = 'no_data_found';
  end if;
  if v_po.status = 'APPROVED' then
    return v_po.po_no;
  end if;
  if v_po.status <> 'DRAFT' then
    raise exception 'Only a draft purchase order can be approved' using errcode = 'restrict_violation';
  end if;

  perform purch.recompute_po_totals(v_po.id);
  select * into v_po from purch.purchase_orders where id = v_po.id;

  if not exists (select 1 from purch.purchase_order_lines where po_id = v_po.id) then
    raise exception 'A purchase order needs at least one line' using errcode = 'check_violation';
  end if;

  select * into v_supplier from app.suppliers where id = v_po.supplier_id;
  if not v_supplier.is_active then
    raise exception 'Supplier % is inactive', v_supplier.code using errcode = 'restrict_violation';
  end if;
  if v_supplier.approval_status <> 'APPROVED' then
    raise exception 'Supplier % is not approved for purchasing (%)',
      v_supplier.code, v_supplier.approval_status
      using errcode = 'restrict_violation';
  end if;
  if v_supplier.approval_expires_on is not null
     and v_supplier.approval_expires_on < v_po.order_date then
    raise exception 'Supplier % approval expired on %',
      v_supplier.code, v_supplier.approval_expires_on
      using errcode = 'restrict_violation';
  end if;
  if v_supplier.entity_id <> v_po.entity_id then
    raise exception 'Supplier does not belong to this entity' using errcode = 'restrict_violation';
  end if;

  v_po_no := app.next_document_number(v_po.entity_id, 'PO', v_po.order_date);

  perform set_config('purch.allow_status_change', 'on', true);

  update purch.purchase_orders
     set status = 'APPROVED',
         po_no = v_po_no,
         approved_at = now(),
         approved_by = app.acting_user_id()
   where id = v_po.id;

  perform set_config('purch.allow_status_change', '', true);

  return v_po_no;
end;
$$;

