create or replace view purch.v_bill_balances
with (security_invoker = true) as
select
  b.id,
  b.entity_id,
  b.total,
  coalesce((
    select sum(a.amount)
      from purch.supplier_payment_allocations a
      join purch.supplier_payments p on p.id = a.payment_id
     where a.bill_id = b.id
       and p.status = 'POSTED'
  ), 0) as allocated,
  b.total - coalesce((
    select sum(a.amount)
      from purch.supplier_payment_allocations a
      join purch.supplier_payments p on p.id = a.payment_id
     where a.bill_id = b.id
       and p.status = 'POSTED'
  ), 0) as outstanding
from purch.bills b;

comment on view purch.v_bill_balances is
  'Posted-bill outstanding after posted supplier payments only. Reversed payments do not reduce the balance.';

