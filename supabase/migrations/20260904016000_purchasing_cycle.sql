-- ===========================================================================
-- Purchasing payables cycle: POs, goods receipts, bills and supplier payments.
--
-- A purchase order is a commitment document only — it does not post the ledger.
-- Goods receipt posts inventory via inv.post_movement(RECEIPT) against GRNI.
-- The supplier bill clears GRNI (when matched to a GRN) or expenses the line,
-- books input VAT, and credits AP. Payments allocate against posted bills.
--
-- Permission mapping (existing catalogue codes; no new permissions here):
--   save_po / cancel draft PO     → procurement.purchase.create
--   approve_po                    → procurement.purchase.approve
--   save/post goods receipt       → procurement.purchase.receive
--   save/post bill                → finance.payment.create
--     (closest existing code; bills are AP documents, not bank payments —
--      finance.payment.create is reused until a dedicated AP bill permission
--      exists. Do not use procurement.purchase.receive for bill posting.)
--   save/post payment             → finance.payment.create
--   reverse_payment               → finance.payment.reverse
--   save/post credit              → finance.payment.create
-- ===========================================================================

set search_path = pg_catalog, public, extensions;

create schema if not exists purch;

comment on schema purch is
  'Supplier documents: purchase orders, goods receipts, bills, payments and credits. Inventory receipts go through inv.post_movement; AP and bank through gl.post_entry.';

