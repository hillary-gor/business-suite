create or replace function purch.save_goods_receipt(p_entity_id uuid, p_payload jsonb)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_id         uuid := nullif(p_payload ->> 'goods_receipt_id', '')::uuid;
  v_supplier   uuid := (p_payload ->> 'supplier_id')::uuid;
  v_po         uuid := nullif(p_payload ->> 'po_id', '')::uuid;
  v_date       date := (p_payload ->> 'receipt_date')::date;
  v_warehouse  uuid := (p_payload ->> 'warehouse_id')::uuid;
  v_line       jsonb;
  v_line_no    integer := 0;
  v_status     purch.grn_status;
  v_po_row     purch.purchase_orders%rowtype;
begin
  -- Permission: procurement.purchase.receive
  perform app.require_permission(p_entity_id, 'procurement.purchase.receive');

  if v_date is null or v_warehouse is null then
    raise exception 'receipt_date and warehouse_id are required' using errcode = 'null_value_not_allowed';
  end if;

  if not exists (
    select 1 from inv.warehouses w
     where w.id = v_warehouse and w.entity_id = p_entity_id and w.is_active
  ) then
    raise exception 'Warehouse was not found in this entity' using errcode = 'no_data_found';
  end if;

  if v_po is not null then
    select * into v_po_row from purch.purchase_orders where id = v_po and entity_id = p_entity_id;
    if not found then
      raise exception 'Purchase order was not found' using errcode = 'no_data_found';
    end if;
    if v_po_row.status <> 'APPROVED' then
      raise exception 'Goods can only be received against an approved purchase order'
        using errcode = 'restrict_violation';
    end if;
    v_supplier := coalesce(v_supplier, v_po_row.supplier_id);
  end if;

  if v_supplier is null then
    raise exception 'supplier_id is required' using errcode = 'null_value_not_allowed';
  end if;

  if not exists (
    select 1 from app.suppliers s
     where s.id = v_supplier and s.entity_id = p_entity_id
  ) then
    raise exception 'Supplier was not found in this entity' using errcode = 'no_data_found';
  end if;

  if v_id is not null then
    select status into v_status from purch.goods_receipts where id = v_id and entity_id = p_entity_id;
    if not found then
      raise exception 'Goods receipt was not found' using errcode = 'no_data_found';
    end if;
    if v_status <> 'DRAFT' then
      raise exception 'Only a draft goods receipt can be saved' using errcode = 'restrict_violation';
    end if;

    update purch.goods_receipts
       set supplier_id = v_supplier,
           po_id = v_po,
           receipt_date = v_date,
           warehouse_id = v_warehouse,
           notes = nullif(p_payload ->> 'notes', ''),
           updated_by = app.acting_user_id()
     where id = v_id;

    delete from purch.goods_receipt_lines where goods_receipt_id = v_id;
  else
    insert into purch.goods_receipts (
      entity_id, supplier_id, po_id, receipt_date, warehouse_id, notes, created_by, updated_by
    ) values (
      p_entity_id, v_supplier, v_po, v_date, v_warehouse,
      nullif(p_payload ->> 'notes', ''),
      app.acting_user_id(), app.acting_user_id()
    )
    returning id into v_id;
  end if;

  if jsonb_typeof(p_payload -> 'lines') = 'array' then
    for v_line in select * from jsonb_array_elements(p_payload -> 'lines')
    loop
      v_line_no := v_line_no + 1;
      if nullif(v_line ->> 'item_id', '') is null then
        raise exception 'Line %: item_id is required', v_line_no using errcode = 'null_value_not_allowed';
      end if;
      if (v_line ->> 'quantity')::numeric is null or (v_line ->> 'quantity')::numeric <= 0 then
        raise exception 'Line %: quantity must be positive', v_line_no using errcode = 'check_violation';
      end if;
      if (v_line ->> 'unit_cost')::numeric is null or (v_line ->> 'unit_cost')::numeric < 0 then
        raise exception 'Line %: unit_cost is required and must be zero or more', v_line_no
          using errcode = 'check_violation';
      end if;
      if length(btrim(coalesce(v_line ->> 'description', ''))) = 0 then
        raise exception 'Line %: description is required', v_line_no using errcode = 'null_value_not_allowed';
      end if;

      insert into purch.goods_receipt_lines (
        entity_id, goods_receipt_id, line_no, po_line_id, item_id, description,
        quantity, unit_cost, bin_id, stock_unit_id, serial_number, condition_code
      ) values (
        p_entity_id, v_id, v_line_no,
        nullif(v_line ->> 'po_line_id', '')::uuid,
        (v_line ->> 'item_id')::uuid,
        btrim(v_line ->> 'description'),
        (v_line ->> 'quantity')::numeric,
        (v_line ->> 'unit_cost')::numeric,
        nullif(v_line ->> 'bin_id', '')::uuid,
        nullif(v_line ->> 'stock_unit_id', '')::uuid,
        nullif(btrim(coalesce(v_line ->> 'serial_number', '')), ''),
        coalesce(nullif(v_line ->> 'condition_code', ''), 'OH')
      );
    end loop;
  end if;

  return v_id;
end;
$$;

create or replace function purch.post_goods_receipt(
  p_grn_id          uuid,
  p_idempotency_key text default null
)
returns text
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_grn        purch.goods_receipts%rowtype;
  v_line       purch.goods_receipt_lines%rowtype;
  v_item       inv.items%rowtype;
  v_bin        uuid;
  v_unit       uuid;
  v_ledger_id  bigint;
  v_grn_no     text;
  v_key        text;
begin
  -- Permission: procurement.purchase.receive
  perform app.require_permission(
    (select entity_id from purch.goods_receipts where id = p_grn_id),
    'procurement.purchase.receive'
  );

  select * into v_grn from purch.goods_receipts where id = p_grn_id for update;
  if not found then
    raise exception 'Goods receipt % does not exist', p_grn_id using errcode = 'no_data_found';
  end if;
  if v_grn.status = 'POSTED' then
    return v_grn.grn_no;
  end if;
  if v_grn.status <> 'DRAFT' then
    raise exception 'Only a draft goods receipt can be posted' using errcode = 'restrict_violation';
  end if;

  if not exists (select 1 from purch.goods_receipt_lines where goods_receipt_id = v_grn.id) then
    raise exception 'A goods receipt needs at least one line' using errcode = 'check_violation';
  end if;

  v_grn_no := app.next_document_number(v_grn.entity_id, 'GRN', v_grn.receipt_date);

  for v_line in
    select * from purch.goods_receipt_lines
     where goods_receipt_id = v_grn.id
     order by line_no
  loop
    select * into v_item from inv.items where id = v_line.item_id and entity_id = v_grn.entity_id;
    if not found then
      raise exception 'Line %: item was not found', v_line.line_no using errcode = 'no_data_found';
    end if;

    v_bin := v_line.bin_id;
    if v_bin is null then
      select id into v_bin
        from inv.bins
       where warehouse_id = v_grn.warehouse_id
         and code = 'MAIN'
         and is_active
       limit 1;
    end if;

    v_unit := v_line.stock_unit_id;

    if v_item.tracking_mode = 'SERIAL' then
      if v_line.quantity <> 1 then
        raise exception 'Line %: serialised receipts are one unit at a time', v_line.line_no
          using errcode = 'check_violation';
      end if;

      if v_unit is null then
        if length(btrim(coalesce(v_line.serial_number, ''))) = 0 then
          raise exception 'Line %: serial_number is required for a serialised item', v_line.line_no
            using errcode = 'null_value_not_allowed';
        end if;
        if v_bin is null then
          raise exception 'Line %: a bin is required to create a stock unit', v_line.line_no
            using errcode = 'null_value_not_allowed';
        end if;

        insert into inv.stock_units (
          entity_id, item_id, serial_number, condition_code, status,
          warehouse_id, bin_id, supplier_id, received_date,
          acquisition_currency, acquisition_cost, unit_cost_base, created_by
        ) values (
          v_grn.entity_id, v_line.item_id, v_line.serial_number,
          coalesce(v_line.condition_code, 'OH'), 'ON_HAND',
          v_grn.warehouse_id, v_bin, v_grn.supplier_id, v_grn.receipt_date,
          (select base_currency_code from app.entities where id = v_grn.entity_id),
          v_line.unit_cost, v_line.unit_cost, app.acting_user_id()
        )
        returning id into v_unit;

        update purch.goods_receipt_lines
           set stock_unit_id = v_unit
         where id = v_line.id;
      end if;
    end if;

    v_key := case
      when p_idempotency_key is not null then p_idempotency_key || ':grn-line:' || v_line.line_no
      else null
    end;

    v_ledger_id := inv.post_movement(
      p_entity_id => v_grn.entity_id,
      p_item_id => v_line.item_id,
      p_warehouse_id => v_grn.warehouse_id,
      p_movement_type => 'RECEIPT',
      p_movement_date => v_grn.receipt_date,
      p_quantity => v_line.quantity,
