-- ===========================================================================
-- Sales documents: quotations, orders, credit/debit notes, refunds, statements.
--
-- Quotations and sales orders are commercial documents only — no GL.
-- Credit notes reverse AR / revenue / output tax (mirror of invoice issue).
-- Debit notes increase AR simply. Refunds pay money out (reverse of receipt).
--
-- Permissions (reuse existing catalogue):
--   save/send/accept/cancel quote, convert   → sales.invoice.create / issue
--   save/confirm/cancel order, convert       → sales.invoice.create / issue
--   save/post credit or debit note           → sales.invoice.create / issue
--   save/post refund                         → sales.payment.create
-- ===========================================================================

set search_path = pg_catalog, public, extensions;

