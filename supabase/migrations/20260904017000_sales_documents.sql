language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_rf         sales.refunds%rowtype;
  v_customer   app.customers%rowtype;
  v_ar         uuid;
  v_bank       gl.accounts%rowtype;
  v_entry_id   uuid;
  v_refund_no  text;
begin
  perform app.require_permission(
    (select entity_id from sales.refunds where id = p_refund_id),
