create or replace function sales.save_quotation(p_entity_id uuid, p_payload jsonb)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_id       uuid := nullif(p_payload ->> 'quotation_id', '')::uuid;
  v_customer uuid := (p_payload ->> 'customer_id')::uuid;
  v_date     date := (p_payload ->> 'quotation_date')::date;
  v_currency char(3);
  v_line     jsonb;
  v_line_no  integer := 0;
  v_qty      numeric;
  v_price    numeric;
  v_net      numeric;
  v_tax      numeric;
  v_rate     numeric;
  v_tax_id   uuid;
  v_status   sales.quotation_status;
begin
  perform app.require_permission(p_entity_id, 'sales.invoice.create');

  if v_customer is null or v_date is null then
    raise exception 'customer_id and quotation_date are required' using errcode = 'null_value_not_allowed';
  end if;

  select coalesce(nullif(p_payload ->> 'currency_code', ''), c.currency_code)
    into v_currency
    from app.customers c
   where c.id = v_customer and c.entity_id = p_entity_id;
  if v_currency is null then
    raise exception 'Customer was not found in this entity' using errcode = 'no_data_found';
  end if;

  if v_id is not null then
    select status into v_status from sales.quotations where id = v_id and entity_id = p_entity_id;
    if not found then raise exception 'Quotation was not found' using errcode = 'no_data_found'; end if;
    if v_status <> 'DRAFT' then
      raise exception 'Only a draft quotation can be saved' using errcode = 'restrict_violation';
    end if;

    update sales.quotations
       set customer_id = v_customer,
           quotation_date = v_date,
           valid_until = nullif(p_payload ->> 'valid_until', '')::date,
           currency_code = v_currency,
           payment_terms_id = nullif(p_payload ->> 'payment_terms_id', '')::uuid,
           warehouse_id = nullif(p_payload ->> 'warehouse_id', '')::uuid,
           notes = nullif(p_payload ->> 'notes', ''),
           updated_by = app.acting_user_id()
     where id = v_id;
    delete from sales.quotation_lines where quotation_id = v_id;
  else
    insert into sales.quotations (
      entity_id, customer_id, quotation_date, valid_until, currency_code,
      payment_terms_id, warehouse_id, notes, created_by, updated_by
    ) values (
      p_entity_id, v_customer, v_date, nullif(p_payload ->> 'valid_until', '')::date, v_currency,
      nullif(p_payload ->> 'payment_terms_id', '')::uuid,
      nullif(p_payload ->> 'warehouse_id', '')::uuid,
      nullif(p_payload ->> 'notes', ''),
      app.acting_user_id(), app.acting_user_id()
    ) returning id into v_id;
  end if;

  if jsonb_typeof(p_payload -> 'lines') = 'array' then
    for v_line in select * from jsonb_array_elements(p_payload -> 'lines')
    loop
      v_line_no := v_line_no + 1;
      v_qty := (v_line ->> 'quantity')::numeric;
      v_price := (v_line ->> 'unit_price')::numeric;
      if v_qty is null or v_qty <= 0 or v_price is null or v_price < 0 then
        raise exception 'Line %: quantity must be positive and unit_price must be zero or more', v_line_no
          using errcode = 'check_violation';
      end if;
      if length(btrim(coalesce(v_line ->> 'description', ''))) = 0 then
        raise exception 'Line %: description is required', v_line_no using errcode = 'null_value_not_allowed';
      end if;
      v_net := round(v_qty * v_price, 4);
      v_tax_id := nullif(v_line ->> 'tax_code_id', '')::uuid;
      v_rate := 0;
      if v_tax_id is not null then
        select t.rate into v_rate from app.tax_codes t
         where t.id = v_tax_id and t.entity_id = p_entity_id and t.is_active;
        if not found then
          raise exception 'Line %: tax code was not found', v_line_no using errcode = 'no_data_found';
        end if;
      end if;
      v_tax := round(v_net * coalesce(v_rate, 0), 4);
      insert into sales.quotation_lines (
        entity_id, quotation_id, line_no, item_id, description,
        quantity, unit_price, tax_code_id, tax_amount, line_net, revenue_account_id
      ) values (
        p_entity_id, v_id, v_line_no,
        nullif(v_line ->> 'item_id', '')::uuid,
        btrim(v_line ->> 'description'),
        v_qty, v_price, v_tax_id, v_tax, v_net,
        nullif(v_line ->> 'revenue_account_id', '')::uuid
      );
    end loop;
  end if;

  perform sales.recompute_quotation_totals(v_id);
  return v_id;
end;
$$;

