      entity_id, customer_id, credit_date, currency_code, warehouse_id,
      invoice_id, notes, restock, created_by, updated_by
    ) values (
      p_entity_id, v_customer, v_date, v_currency,
      nullif(p_payload ->> 'warehouse_id', '')::uuid,
      nullif(p_payload ->> 'invoice_id', '')::uuid,
      nullif(p_payload ->> 'notes', ''),
      coalesce((p_payload ->> 'restock')::boolean, false),
      app.acting_user_id(), app.acting_user_id()
    ) returning id into v_id;
  end if;

  if jsonb_typeof(p_payload -> 'lines') = 'array' then
    for v_line in select * from jsonb_array_elements(p_payload -> 'lines')
    loop
      v_line_no := v_line_no + 1;
      v_qty := (v_line ->> 'quantity')::numeric;
      v_price := (v_line ->> 'unit_price')::numeric;
      if v_qty is null or v_qty <= 0 or v_price is null or v_price < 0 then
        raise exception 'Line %: quantity must be positive and unit_price must be zero or more', v_line_no
          using errcode = 'check_violation';
      end if;
      if length(btrim(coalesce(v_line ->> 'description', ''))) = 0 then
        raise exception 'Line %: description is required', v_line_no using errcode = 'null_value_not_allowed';
      end if;
      v_net := round(v_qty * v_price, 4);
      v_tax_id := nullif(v_line ->> 'tax_code_id', '')::uuid;
      v_rate := 0;
      if v_tax_id is not null then
        select t.rate into v_rate from app.tax_codes t
         where t.id = v_tax_id and t.entity_id = p_entity_id and t.is_active;
        if not found then
          raise exception 'Line %: tax code was not found', v_line_no using errcode = 'no_data_found';
        end if;
      end if;
      v_tax := round(v_net * coalesce(v_rate, 0), 4);
      insert into sales.credit_note_lines (
        entity_id, credit_note_id, line_no, item_id, description,
        quantity, unit_price, tax_code_id, tax_amount, line_net,
        revenue_account_id, stock_unit_id, stock_lot_id, unit_cost_base
      ) values (
        p_entity_id, v_id, v_line_no,
        nullif(v_line ->> 'item_id', '')::uuid,
        btrim(v_line ->> 'description'),
        v_qty, v_price, v_tax_id, v_tax, v_net,
        nullif(v_line ->> 'revenue_account_id', '')::uuid,
        nullif(v_line ->> 'stock_unit_id', '')::uuid,
        nullif(v_line ->> 'stock_lot_id', '')::uuid,
        nullif(v_line ->> 'unit_cost_base', '')::numeric
      );
    end loop;
  end if;

  if jsonb_typeof(p_payload -> 'allocations') = 'array' then
    for v_alloc in select * from jsonb_array_elements(p_payload -> 'allocations')
    loop
      insert into sales.credit_note_allocations (entity_id, credit_note_id, invoice_id, amount)
      values (
        p_entity_id, v_id,
        (v_alloc ->> 'invoice_id')::uuid,
        (v_alloc ->> 'amount')::numeric
      );
    end loop;
  end if;

  perform sales.recompute_credit_note_totals(v_id);
  return v_id;
end;
$$;

create or replace function sales.post_credit_note(
  p_credit_note_id  uuid,
  p_idempotency_key text default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_cn         sales.credit_notes%rowtype;
  v_customer   app.customers%rowtype;
  v_ar         uuid;
  v_entry_id   uuid;
  v_credit_no  text;
  v_lines      jsonb := '[]'::jsonb;
  v_line       record;
  v_tax        record;
  v_revenue    uuid;
  v_alloc      record;
  v_key        text;
begin
  perform app.require_permission(
    (select entity_id from sales.credit_notes where id = p_credit_note_id),
    'sales.invoice.issue'
  );

  select * into v_cn from sales.credit_notes where id = p_credit_note_id for update;
  if not found then raise exception 'Credit note was not found' using errcode = 'no_data_found'; end if;
  if v_cn.status = 'POSTED' then return v_cn.journal_entry_id; end if;
  if v_cn.status <> 'DRAFT' then
    raise exception 'Only a draft credit note can be posted' using errcode = 'restrict_violation';
  end if;

  perform sales.recompute_credit_note_totals(v_cn.id);
  select * into v_cn from sales.credit_notes where id = v_cn.id;

  if v_cn.total <= 0 then
    raise exception 'A credit note needs at least one line with a positive amount'
      using errcode = 'check_violation';
  end if;

  select * into v_customer from app.customers where id = v_cn.customer_id;
  v_ar := sales.ar_account(v_cn.entity_id, v_cn.customer_id);

  for v_alloc in
    select a.invoice_id, a.amount, i.invoice_no, i.status, i.customer_id, i.currency_code, bal.outstanding
      from sales.credit_note_allocations a
      join sales.invoices i on i.id = a.invoice_id
      join sales.v_invoice_balances bal on bal.id = i.id
     where a.credit_note_id = v_cn.id
  loop
    if v_alloc.status <> 'ISSUED' then
      raise exception 'Credits can only be applied to issued invoices' using errcode = 'restrict_violation';
    end if;
    if v_alloc.customer_id <> v_cn.customer_id then
      raise exception 'Invoice % belongs to a different customer', v_alloc.invoice_no
        using errcode = 'restrict_violation';
    end if;
    if v_alloc.currency_code <> v_cn.currency_code then
      raise exception 'Invoice % currency mismatch', v_alloc.invoice_no
        using errcode = 'check_violation';
    end if;
    if v_alloc.amount > v_alloc.outstanding then
      raise exception 'Allocation of % to invoice % exceeds outstanding %',
        v_alloc.amount, v_alloc.invoice_no, v_alloc.outstanding
        using errcode = 'check_violation';
    end if;
  end loop;

  -- Optional restock via CUSTOMER_RETURN (positive inbound quantity).
  if v_cn.restock then
    if v_cn.warehouse_id is null then
      raise exception 'Restock requires warehouse_id' using errcode = 'null_value_not_allowed';
    end if;
    for v_line in
      select * from sales.credit_note_lines
       where credit_note_id = v_cn.id
         and item_id is not null
         and (stock_unit_id is not null or stock_lot_id is not null or unit_cost_base is not null)
       order by line_no
    loop
      v_key := case when p_idempotency_key is not null
        then p_idempotency_key || ':return:' || v_line.line_no else null end;
      perform inv.post_movement(
        p_entity_id => v_cn.entity_id,
        p_item_id => v_line.item_id,
        p_warehouse_id => v_cn.warehouse_id,
        p_movement_type => 'CUSTOMER_RETURN',
        p_movement_date => v_cn.credit_date,
        p_quantity => v_line.quantity,
        p_stock_unit_id => v_line.stock_unit_id,
        p_stock_lot_id => v_line.stock_lot_id,
        p_unit_cost_base => v_line.unit_cost_base,
        p_source_type => 'SALES_CREDIT_NOTE',
        p_source_id => v_cn.id,
        p_source_line_id => v_line.id,
        p_reference => null,
        p_notes => v_line.description,
        p_idempotency_key => v_key
      );
    end loop;
  end if;

  -- Reverse of invoice: DR revenue, DR output tax, CR AR.
  for v_line in
    select l.* from sales.credit_note_lines l
     where l.credit_note_id = v_cn.id order by l.line_no
  loop
    v_revenue := coalesce(
      v_line.revenue_account_id,
      (select i.revenue_account_id from inv.items i where i.id = v_line.item_id),
      gl.setting_account(v_cn.entity_id, 'DEFAULT_REVENUE')
    );
    v_lines := v_lines || jsonb_build_object(
      'account_id', v_revenue,
      'currency_code', v_cn.currency_code,
      'debit', v_line.line_net,
      'credit', 0,
      'memo', v_line.description,
      'customer_id', v_cn.customer_id,
      'item_id', v_line.item_id
    );
  end loop;

  for v_tax in
    select t.output_tax_account_id as account_id, sum(l.tax_amount) as amount
      from sales.credit_note_lines l
      join app.tax_codes t on t.id = l.tax_code_id
     where l.credit_note_id = v_cn.id and l.tax_amount > 0
     group by t.output_tax_account_id
  loop
    if v_tax.account_id is null then
      raise exception 'Tax code is missing an output tax account' using errcode = 'no_data_found';
    end if;
    v_lines := v_lines || jsonb_build_object(
      'account_id', v_tax.account_id,
      'currency_code', v_cn.currency_code,
      'debit', v_tax.amount,
      'credit', 0,
      'memo', 'Output tax reversal',
      'customer_id', v_cn.customer_id
    );
  end loop;

  v_lines := v_lines || jsonb_build_object(
    'account_id', v_ar,
    'currency_code', v_cn.currency_code,
    'debit', 0,
    'credit', v_cn.total,
    'memo', 'Accounts receivable',
    'customer_id', v_cn.customer_id
  );

  v_credit_no := app.next_document_number(v_cn.entity_id, 'CN', v_cn.credit_date);

  v_entry_id := gl.post_entry(
    v_cn.entity_id,
    jsonb_build_object(
      'entry_date', v_cn.credit_date,
      'source_type', 'SALES_CREDIT_NOTE',
      'source_id', v_cn.id,
      'source_document_no', v_credit_no,
      'description', 'Credit note ' || v_credit_no || ' · ' || v_customer.legal_name,
      'lines', v_lines
    ),
    p_idempotency_key
  );

  perform set_config('sales.allow_status_change', 'on', true);
  update sales.credit_notes
     set status = 'POSTED', credit_no = v_credit_no, journal_entry_id = v_entry_id
   where id = v_cn.id;
  perform set_config('sales.allow_status_change', '', true);

  return v_entry_id;
end;
$$;

