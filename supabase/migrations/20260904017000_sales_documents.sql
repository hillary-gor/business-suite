create or replace function sales.fn_guard_doc_status()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if tg_op = 'DELETE' then
    if old.status::text not in ('DRAFT') then
      raise exception 'Only a draft document can be deleted'
        using errcode = 'restrict_violation';
    end if;
    return old;
  end if;

  if current_setting('sales.allow_status_change', true) is distinct from 'on' then
    if tg_op = 'UPDATE' and old.status::text <> 'DRAFT' then
      raise exception 'A non-draft document cannot be amended'
        using errcode = 'restrict_violation';
    end if;
    if new.status is distinct from coalesce(old.status, new.status) then
      raise exception 'Change document status through the sales.* functions'
        using errcode = 'restrict_violation';
    end if;
  end if;

  return new;
end;
$$;

