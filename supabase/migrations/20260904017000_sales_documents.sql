create or replace function sales.ar_account(p_entity_id uuid, p_customer_id uuid)
returns uuid
language plpgsql
stable
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_ar uuid;
begin
  select coalesce(
    c.ar_account_id,
    (select a.id from gl.accounts a
      where a.entity_id = p_entity_id
        and a.control_type = 'ACCOUNTS_RECEIVABLE'
        and a.is_postable
      order by a.code
      limit 1)
  ) into v_ar
  from app.customers c
  where c.id = p_customer_id and c.entity_id = p_entity_id;

  if v_ar is null then
    raise exception 'No receivables control account is configured' using errcode = 'no_data_found';
  end if;
  return v_ar;
end;
$$;

create or replace function sales.recompute_quotation_totals(p_id uuid)
returns void language plpgsql set search_path = pg_catalog, public as $$
begin
  update sales.quotations q
     set subtotal = coalesce(x.subtotal, 0),
         tax_total = coalesce(x.tax_total, 0),
         total = coalesce(x.subtotal, 0) + coalesce(x.tax_total, 0)
    from (
      select quotation_id, sum(line_net) as subtotal, sum(tax_amount) as tax_total
        from sales.quotation_lines where quotation_id = p_id group by quotation_id
    ) x
   where q.id = p_id and q.id = x.quotation_id;
  if not found then
    update sales.quotations set subtotal = 0, tax_total = 0, total = 0 where id = p_id;
  end if;
end;
$$;

create or replace function sales.recompute_sales_order_totals(p_id uuid)
returns void language plpgsql set search_path = pg_catalog, public as $$
begin
  update sales.sales_orders o
     set subtotal = coalesce(x.subtotal, 0),
         tax_total = coalesce(x.tax_total, 0),
         total = coalesce(x.subtotal, 0) + coalesce(x.tax_total, 0)
    from (
      select sales_order_id, sum(line_net) as subtotal, sum(tax_amount) as tax_total
        from sales.sales_order_lines where sales_order_id = p_id group by sales_order_id
    ) x
   where o.id = p_id and o.id = x.sales_order_id;
  if not found then
    update sales.sales_orders set subtotal = 0, tax_total = 0, total = 0 where id = p_id;
  end if;
end;
$$;

create or replace function sales.recompute_credit_note_totals(p_id uuid)
returns void language plpgsql set search_path = pg_catalog, public as $$
begin
  update sales.credit_notes c
     set subtotal = coalesce(x.subtotal, 0),
         tax_total = coalesce(x.tax_total, 0),
         total = coalesce(x.subtotal, 0) + coalesce(x.tax_total, 0)
    from (
      select credit_note_id, sum(line_net) as subtotal, sum(tax_amount) as tax_total
        from sales.credit_note_lines where credit_note_id = p_id group by credit_note_id
    ) x
   where c.id = p_id and c.id = x.credit_note_id;
  if not found then
    update sales.credit_notes set subtotal = 0, tax_total = 0, total = 0 where id = p_id;
  end if;
end;
$$;

create or replace function sales.recompute_debit_note_totals(p_id uuid)
returns void language plpgsql set search_path = pg_catalog, public as $$
begin
  update sales.debit_notes d
     set subtotal = coalesce(x.subtotal, 0),
         tax_total = coalesce(x.tax_total, 0),
         total = coalesce(x.subtotal, 0) + coalesce(x.tax_total, 0)
    from (
      select debit_note_id, sum(line_net) as subtotal, sum(tax_amount) as tax_total
        from sales.debit_note_lines where debit_note_id = p_id group by debit_note_id
    ) x
   where d.id = p_id and d.id = x.debit_note_id;
  if not found then
    update sales.debit_notes set subtotal = 0, tax_total = 0, total = 0 where id = p_id;
  end if;
end;
$$;

