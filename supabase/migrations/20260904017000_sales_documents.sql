-- Outstanding after receipts AND posted credit-note allocations.
create or replace view sales.v_invoice_balances
with (security_invoker = true) as
select
  i.id,
  i.entity_id,
  i.total,
  coalesce((
    select sum(a.amount)
      from sales.receipt_allocations a
      join sales.receipts r on r.id = a.receipt_id
     where a.invoice_id = i.id and r.status = 'POSTED'
  ), 0)
  + coalesce((
    select sum(a.amount)
      from sales.credit_note_allocations a
      join sales.credit_notes c on c.id = a.credit_note_id
     where a.invoice_id = i.id and c.status = 'POSTED'
  ), 0) as allocated,
  i.total
  - coalesce((
    select sum(a.amount)
      from sales.receipt_allocations a
      join sales.receipts r on r.id = a.receipt_id
     where a.invoice_id = i.id and r.status = 'POSTED'
  ), 0)
  - coalesce((
    select sum(a.amount)
      from sales.credit_note_allocations a
      join sales.credit_notes c on c.id = a.credit_note_id
     where a.invoice_id = i.id and c.status = 'POSTED'
  ), 0) as outstanding
from sales.invoices i;

comment on view sales.v_invoice_balances is
  'Issued-invoice outstanding after posted receipts and posted credit-note allocations.';

