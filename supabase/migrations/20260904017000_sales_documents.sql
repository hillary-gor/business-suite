  v_refund_no := app.next_document_number(v_rf.entity_id, 'RF', v_rf.refund_date);

  -- Money out: DR AR, CR bank (reverse of receipt which is DR bank / CR AR).
  v_entry_id := gl.post_entry(
    v_rf.entity_id,
    jsonb_build_object(
      'entry_date', v_rf.refund_date,
      'source_type', 'CUSTOMER_REFUND',
      'source_id', v_rf.id,
      'source_document_no', v_refund_no,
      'description', 'Refund ' || v_refund_no || ' · ' || v_customer.legal_name,
      'lines', jsonb_build_array(
        jsonb_build_object(
          'account_id', v_ar,
          'currency_code', v_rf.currency_code,
          'debit', v_rf.amount,
          'credit', 0,
          'memo', 'Accounts receivable',
          'customer_id', v_rf.customer_id
        ),
        jsonb_build_object(
          'account_id', v_rf.bank_account_id,
          'currency_code', v_rf.currency_code,
          'debit', 0,
          'credit', v_rf.amount,
          'memo', coalesce(v_rf.memo, 'Customer refund'),
          'customer_id', v_rf.customer_id
        )
      )
    ),
    p_idempotency_key
  );

  perform set_config('sales.allow_status_change', 'on', true);
  update sales.refunds
     set status = 'POSTED', refund_no = v_refund_no, journal_entry_id = v_entry_id
   where id = v_rf.id;
  perform set_config('sales.allow_status_change', '', true);
  return v_entry_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- Customer statement
-- ---------------------------------------------------------------------------

create or replace function sales.customer_statement(
  p_entity_id   uuid,
  p_customer_id uuid,
  p_as_of       date default current_date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_result jsonb;
begin
  perform app.require_permission(p_entity_id, 'sales.invoice.create');

  if not exists (
    select 1 from app.customers c
     where c.id = p_customer_id and c.entity_id = p_entity_id
  ) then
    raise exception 'Customer was not found in this entity' using errcode = 'no_data_found';
  end if;

  select jsonb_build_object(
    'customer_id', p_customer_id,
    'as_of', p_as_of,
    'open_invoices', coalesce((
      select jsonb_agg(jsonb_build_object(
        'invoice_id', i.id,
        'invoice_no', i.invoice_no,
        'invoice_date', i.invoice_date,
        'due_date', i.due_date,
        'total', i.total,
        'outstanding', bal.outstanding,
        'currency_code', i.currency_code
      ) order by i.invoice_date, i.invoice_no)
        from sales.invoices i
        join sales.v_invoice_balances bal on bal.id = i.id
       where i.entity_id = p_entity_id
         and i.customer_id = p_customer_id
         and i.status = 'ISSUED'
         and i.invoice_date <= p_as_of
         and bal.outstanding > 0
    ), '[]'::jsonb),
    'recent_activity', coalesce((
      select jsonb_agg(x.row order by x.sort_date desc, x.doc_no)
        from (
          select i.invoice_date as sort_date, i.invoice_no as doc_no,
                 jsonb_build_object(
                   'type', 'INVOICE',
                   'id', i.id,
                   'doc_no', i.invoice_no,
                   'doc_date', i.invoice_date,
                   'amount', i.total,
                   'status', i.status::text
                 ) as row
            from sales.invoices i
           where i.entity_id = p_entity_id and i.customer_id = p_customer_id
             and i.invoice_date <= p_as_of and i.status in ('ISSUED', 'VOIDED')
          union all
          select r.receipt_date, r.receipt_no,
                 jsonb_build_object(
                   'type', 'RECEIPT',
                   'id', r.id,
                   'doc_no', r.receipt_no,
                   'doc_date', r.receipt_date,
                   'amount', r.amount,
                   'status', r.status::text
                 )
            from sales.receipts r
           where r.entity_id = p_entity_id and r.customer_id = p_customer_id
             and r.receipt_date <= p_as_of and r.status = 'POSTED'
          union all
          select c.credit_date, c.credit_no,
                 jsonb_build_object(
                   'type', 'CREDIT_NOTE',
                   'id', c.id,
                   'doc_no', c.credit_no,
                   'doc_date', c.credit_date,
                   'amount', c.total,
                   'status', c.status::text
                 )
            from sales.credit_notes c
           where c.entity_id = p_entity_id and c.customer_id = p_customer_id
             and c.credit_date <= p_as_of and c.status = 'POSTED'
          union all
          select d.debit_date, d.debit_no,
                 jsonb_build_object(
                   'type', 'DEBIT_NOTE',
                   'id', d.id,
                   'doc_no', d.debit_no,
                   'doc_date', d.debit_date,
                   'amount', d.total,
                   'status', d.status::text
                 )
            from sales.debit_notes d
           where d.entity_id = p_entity_id and d.customer_id = p_customer_id
             and d.debit_date <= p_as_of and d.status = 'POSTED'
          union all
          select f.refund_date, f.refund_no,
                 jsonb_build_object(
                   'type', 'REFUND',
                   'id', f.id,
                   'doc_no', f.refund_no,
                   'doc_date', f.refund_date,
                   'amount', f.amount,
                   'status', f.status::text
                 )
            from sales.refunds f
           where f.entity_id = p_entity_id and f.customer_id = p_customer_id
             and f.refund_date <= p_as_of and f.status = 'POSTED'
        ) x
    ), '[]'::jsonb)
  ) into v_result;

  return v_result;
end;
$$;

