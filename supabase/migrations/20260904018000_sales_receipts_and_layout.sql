create or replace function sales.fn_guard_sales_receipt()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'DRAFT' then
      raise exception 'Only a draft sales receipt can be deleted'
        using errcode = 'restrict_violation';
    end if;
    return old;
  end if;

  if tg_op = 'UPDATE'
     and old.status is distinct from new.status
     and current_setting('sales.allow_status_change', true) is distinct from 'on' then
    raise exception 'Change sales receipt status through sales.post_sales_receipt / void_sales_receipt'
      using errcode = 'restrict_violation';
  end if;

  if tg_op = 'UPDATE' and old.status <> 'DRAFT' and new.status = old.status then
    if current_setting('sales.allow_status_change', true) is distinct from 'on' then
      raise exception 'A posted sales receipt cannot be amended'
        using errcode = 'restrict_violation';
    end if;
  end if;

  return new;
end;
$$;

create trigger sales_receipts_guard
  before insert or update or delete on sales.sales_receipts
  for each row execute function sales.fn_guard_sales_receipt();

create or replace function sales.fn_guard_sales_receipt_line()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
declare
  v_status sales.sales_receipt_status;
begin
  select status into v_status
    from sales.sales_receipts
   where id = coalesce(new.sales_receipt_id, old.sales_receipt_id);
  if v_status <> 'DRAFT' then
    raise exception 'Lines on a non-draft sales receipt cannot be amended'
      using errcode = 'restrict_violation';
  end if;
  return coalesce(new, old);
end;
$$;

create trigger sales_receipt_lines_guard
  before insert or update or delete on sales.sales_receipt_lines
  for each row execute function sales.fn_guard_sales_receipt_line();

