create type sales.sales_receipt_status as enum ('DRAFT', 'POSTED', 'VOIDED');

create table sales.sales_receipts (
  id                 uuid primary key default gen_random_uuid(),
  entity_id          uuid not null references app.entities (id) on delete restrict,
  receipt_no         text,
  status             sales.sales_receipt_status not null default 'DRAFT',
  customer_id        uuid not null references app.customers (id) on delete restrict,
  receipt_date       date not null,
  currency_code      char(3) not null references app.currencies (code),
  payment_terms_id   uuid references app.payment_terms (id) on delete restrict,
  warehouse_id       uuid references inv.warehouses (id) on delete restrict,
  bank_account_id    uuid not null references gl.accounts (id) on delete restrict,
  bill_email         text,
  ship_to_name       text,
  ship_to_address    text,
  customer_po        text,
  notes              text,
  subtotal           app.money_amount not null default 0 check (subtotal >= 0),
  tax_total          app.money_amount not null default 0 check (tax_total >= 0),
  total              app.money_amount not null default 0 check (total >= 0),
  journal_entry_id   uuid references gl.journal_entry (id) on delete restrict,
  void_reason        text,
  voided_at          timestamptz,
  voided_by          uuid references app.users (id),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  created_by         uuid,
  updated_by         uuid,
  unique (entity_id, receipt_no),
  constraint sales_receipts_posted_has_number check (status = 'DRAFT' or receipt_no is not null),
  constraint sales_receipts_posted_has_journal check (status <> 'POSTED' or journal_entry_id is not null),
  constraint sales_receipts_void_has_reason check (
    status <> 'VOIDED' or length(btrim(coalesce(void_reason, ''))) > 0
  )
);

create table sales.sales_receipt_lines (
  id                 uuid primary key default gen_random_uuid(),
  entity_id          uuid not null references app.entities (id) on delete restrict,
  sales_receipt_id   uuid not null references sales.sales_receipts (id) on delete cascade,
  line_no            integer not null check (line_no > 0),
  item_id            uuid references inv.items (id) on delete restrict,
  description        text not null check (length(btrim(description)) > 0),
  service_date       date,
  quantity           app.quantity not null check (quantity > 0),
  unit_price         app.money_amount not null check (unit_price >= 0),
  tax_code_id        uuid references app.tax_codes (id) on delete restrict,
  tax_amount         app.money_amount not null default 0 check (tax_amount >= 0),
  line_net           app.money_amount not null default 0 check (line_net >= 0),
  revenue_account_id uuid references gl.accounts (id) on delete restrict,
  stock_unit_id      uuid references inv.stock_units (id) on delete restrict,
  stock_lot_id       uuid references inv.stock_lots (id) on delete restrict,
  created_at         timestamptz not null default now(),
  unique (sales_receipt_id, line_no)
);

